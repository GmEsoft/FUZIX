#!/usr/bin/env python3
"""Generate the shared firmware / immutable image / Dhara flash geometry."""
import argparse
import hashlib
import json
from pathlib import Path

FLASH_BASE = 0x10000000
ERASE_SIZE = 4096
PAGE_SIZE = 512
GC_RATIO = 10


def layout(flash_bytes, firmware_kib, xip_kib):
    firmware = firmware_kib * 1024
    xip = xip_kib * 1024
    if flash_bytes <= 0 or firmware <= 0 or xip < 0:
        raise ValueError("flash and firmware must be positive; XIP must be nonnegative")
    if any(n % ERASE_SIZE for n in (flash_bytes, firmware, xip)):
        raise ValueError("all flash regions must be aligned to 4096-byte erase sectors")
    ftl_offset = firmware + xip
    if ftl_offset >= flash_bytes or flash_bytes > 0x01000000:
        raise ValueError("regions exceed flash capacity (maximum 16 MiB XIP window)")
    values = dict(version=1, flash_base=FLASH_BASE, flash_bytes=flash_bytes,
                  erase_bytes=ERASE_SIZE, page_bytes=PAGE_SIZE, gc_ratio=GC_RATIO,
                  firmware_offset=0, firmware_bytes=firmware,
                  xip_offset=firmware, xip_bytes=xip,
                  ftl_offset=ftl_offset, ftl_bytes=flash_bytes - ftl_offset)
    identity = hashlib.sha256(json.dumps(values, sort_keys=True).encode()).hexdigest()
    values["layout_id"] = identity
    return values


def generate(values, out):
    out.mkdir(parents=True, exist_ok=True)
    def write(name, data):
        path = out / name
        if not path.exists() or path.read_text() != data:
            path.write_text(data)
    write("flash-layout.json", json.dumps(values, indent=2) + "\n")
    header = ["/* Generated by flash-layout.py; do not edit. */",
              "#ifndef FUZIX_FLASH_LAYOUT_H", "#define FUZIX_FLASH_LAYOUT_H"]
    for key, value in values.items():
        literal = '"' + value + '"' if isinstance(value, str) else str(value) + "u"
        header.append("#define FUZIX_FLASH_" + key.upper() + " " + literal)
    header.append("#endif")
    write("flash-layout.h", "\n".join(header) + "\n")
    write("flash-layout.env", "\n".join([
        "# Generated flash geometry for image tools.",
        "FLASH_LAYOUT_ID=" + values["layout_id"],
        "FTL_SIZE_KIB=" + str(values["ftl_bytes"] // 1024),
        "FTL_ADDRESS=" + hex(values["flash_base"] + values["ftl_offset"]),
        "FLASH_ERASE_BYTES=" + str(values["erase_bytes"]),
        "FLASH_GC_RATIO=" + str(values["gc_ratio"]),
    ]) + "\n")
    limit = values["flash_base"] + values["firmware_bytes"]
    write("flash-layout.ld", 'ASSERT(__flash_binary_end <= ' + hex(limit) +
          ', "FUZIX firmware overlaps reserved XIP or filesystem flash")\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--flash-bytes", required=True, type=int)
    parser.add_argument("--firmware-kib", type=int, default=96)
    parser.add_argument("--xip-kib", type=int, default=0)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    try:
        generate(layout(args.flash_bytes, args.firmware_kib, args.xip_kib), args.output)
    except ValueError as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
