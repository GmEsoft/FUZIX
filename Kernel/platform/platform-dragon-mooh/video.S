; These are not used yet.
; When we unmap the common page to work on the video below, whatever
; has been written there (kstack in particular) can still be read
; but if anything is written it will be lost once we remap the common.
_map_video:
	tfr	cc,a
	sta	cc_video
	orcc	#$10		; disable interrupt while video is mapped
	lda	#$3F		; since common disappears
	sta	$FFA0		; unmap kernel above video memory
	rts			; return address bled through

_unmap_video:
	ldx	,s		; save return address written to video
	lda	#KBANKV
	sta	$FFA0		; remap kernel
	stx	,s		; rewrite return address
	lda	cc_video
	tfr	a,cc
	rts

;
;	Dragon video drivers
;
;	SAM V2=1 V1=1 V0=-
;	6847 A/G=1 GM2=1 GM1=1 GM0=1
;
_vid256x192:
	sta	$ffc0
	sta	$ffc3
	sta	$ffc5
	lda	$ff22
	anda	#$07
	ora	#$f0
	sta	$ff22
	; shift VDU scanout to 0x0800 = VIDEO_START
	sta	$ffc8+0
	sta	$ffca+1
	rts

;
;	Compute the video base address
;	A = X, B = Y
;
vidaddr:
	ldy	#VIDEO_BASE
	exg	a,b
	leay	d,y		; 256 x Y + X
	rts
;
;	plot_char(int8_t y, int8_t x, uint16_t c)
;
_m6847_plot_char:
	; B = Y so get A = X
	lda	2,s
	bsr	vidaddr	
	; Symbol
	ldb	4,s
plot_patch:
	andb	#0x7f		; mask char - patched on vtattr change
	lslb			; multiply by 8
	rola
	lslb
	rola
	lslb
	rola
	addd	#_fontdata_8x8	; relative to font
	tfr	d,x
	jsr	_map_video
	ldb	_vtattr
	andb	#0x3F		; drop the bits that don't affect our video
	beq	plot_fast

	;
	;	General purpose plot with attributes, we only fastpath
	;	the simple case
	;
	clra
plot_loop:
	sta	_vtrow
	ldb	_vtattr
	cmpa	#7		; Underline only applies on the bottom row
	beq	ul_this
	andb	#0xFD
ul_this:
	cmpa	#3		; italic shift right for < 3
	blt	ital_1
	andb	#0xFB
	bra	maskdone
ital_1:
	cmpa	#5		; italic shift right for >= 5
	blt	maskdone
	bitb	#0x04
	bne	maskdone
	orb	#0x40		; spare bit borrow for bottom of italic
	andb	#0xFB
maskdone:
	lda	,x+		; now throw the row away for a bit
	bitb	#0x10
	bne	notbold
	lsra
	ora	-1,x		; shift and or to make it bold
notbold:
	bitb	#0x04		; italic by shifting top and bottom
	beq	notital1
	lsra
notital1:
	bitb	#0x40
	beq	notital2
	lsla
notital2:
	bitb	#0x02
	beq	notuline
	lda	#0xff		; underline by setting bottom row
notuline:
	bitb	#0x01		; inverse or not: we are really in inverse
	bne	plot_inv	; by default so we complement except if
	coma			; inverted
plot_inv:
	bitb	#0x20		; overstrike or plot ?
	bne	overstrike
	sta	,y
	bra	plotnext
overstrike:
	anda	,y
	sta	,y
plotnext:
	leay	32,y
	lda	_vtrow
	inca
	cmpa	#8
	bne	plot_loop
	jsr	_unmap_video
	rts
;
;	Fast path for normal attributes
;
plot_fast:
	leay	128,y	; saves time later keeping offsets 8-bit
	ldd	,x		; simple 8x8 renderer for now
	coma
	comb
	sta	-128,y
	stb	-96,y
	ldd	2,x
	coma
	comb
	sta	-64,y
	stb	-32,y
	ldd	4,x
	coma
	comb
	sta	,y
	stb	32,y
	ldd	6,x
	coma
	comb
	sta	64,y
	stb	96,y
	jsr	_unmap_video
	rts

;
;	void scroll_up(void)
;
_m6847_scroll_up:
	pshs	u
	ldy	#VIDEO_BASE
	leau	256,y
	jsr	_map_video
vscrolln:
	; Unrolled line by line copy
	pulu	d,x
	std	,y++
	stx	,y++
	pulu	d,x
	std	,y++
	stx	,y++
	pulu	d,x
	std	,y++
	stx	,y++
	pulu	d,x
	std	,y++
	stx	,y++
	pulu	d,x
	std	,y++
	stx	,y++
	pulu	d,x
	std	,y++
	stx	,y++
	pulu	d,x
	std	,y++
	stx	,y++
	pulu	d,x
	std	,y++
	stx	,y++
	cmpu	#VIDEO_END
	bne	vscrolln
	jsr	_unmap_video
	puls	u,pc
;
;	void scroll_down(void)
;
_m6847_scroll_down:
	pshs	u
	ldu	#VIDEO_END
	leay	-256,u
	jsr	_map_video
vscrolld:
	; Unrolled line by line loop
	ldx	,--y
	ldd	,--y
	pshu	d,x
	ldx	,--y
	ldd	,--y
	pshu	d,x
	ldx	,--y
	ldd	,--y
	pshu	d,x
	ldx	,--y
	ldd	,--y
	pshu	d,x
	ldx	,--y
	ldd	,--y
	pshu	d,x
	ldx	,--y
	ldd	,--y
	pshu	d,x
	ldx	,--y
	ldd	,--y
	pshu	d,x
	ldx	,--y
	ldd	,--y
	pshu	d,x
	cmpy	#VIDEO_BASE
	bne	vscrolld
	jsr	_unmap_video
	puls	u,pc

;
;	clear_across(int8_t y, int8_t x, uint16_t l)
;
_m6847_clear_across:
	lda	2,s	; x into A, B already has y
	jsr	vidaddr	; Y now holds the address
	ldd	3,s	; Counter is in D
	jsr	_map_video
	lda	#0xff
	leay	128,y	; saves time later keeping offsets 8-bit
clearnext:
	sta	-128,y
	sta	-96,y
	sta	-64,y
	sta	-32,y
	sta	,y+
	sta	31,y
	sta	63,y
	sta	95,y
	decb
	bne	clearnext
	jmp 	unmap_video
;
;	clear_lines(int8_t y, int8_t ct)
;
_m6847_clear_lines:
	clra			; b holds Y pos already
	jsr	vidaddr		; y now holds ptr to line start
	ldb	2,s		; get count
	beq	no_lines
	lslb
	lslb
	lslb
	jsr	_map_video
	ldx	#0xffff
	; Would be faster to use ,u and start at end and pshu x,d ?
wipel:
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	stx	,y++
	decb			; count of lines
	bne	wipel
	jmp	unmap_video

_m6847_cursor_on:
	lda	2,s
	jsr	vidaddr
	leax	,y
	stx	cursor_save
	; Fall through
_m6847_cursor_off:
	jsr	_map_video
	ldb	_vtattr
	bitb	#0x80
	bne	nocursor
	ldx	cursor_save
	leax	128,x	; saves time later keeping offsets 8-bit
	com	-128,x
	com	-96,x
	com	-64,x
	com	-32,x
	com	,x
	com	32,x
	com	64,x
	com	96,x
nocursor:
	jmp	_unmap_video

_m6847_vtattr_notify:
	lda	_vtattr
	anda	#0x40		; VTA_ALTCHAR
	beq	lowchar
        ldd	#0xCA80
	bra	setmode
lowchar:
        ldd	#0xC47F
setmode
	std	plot_patch
_m6847_cursor_disable:
no_lines:
	rts
;
;	These routines work in both 256x192x2 and 128x192x4 modes
;	because everything in the X plane is byte-wide.
;
_m6847_video_write:
	clra			; clr C
	bra	tfr_cmd
_m6847_video_read:
	coma			; set C
	bra	tfr_cmd		; go

;;; This does the job of READ & WRITE
;;;   takes: C = direction 0=write, 1=read
;;;   takes: X = transfer buffer ptr + 2
tfr_cmd:
	tfr	d,x
	pshs	cc,u		; save regs
	orcc	#$10		; turn off interrupt - int might remap kernel
	lda	#$3F
	sta	$FFA0		; unmap kernel above video memory
	ldd	#$80c0		; this is writing
	bcc	c@		; if carry clear then keep D write
	exg	a,b		; else flip D: now is reading
c@	sta	b@+1		; !!! self modify inner loop
	stb	b@+3		; !!!  
	bsr	vidptr		; U = screen addr
	leay	,x		; Y = ptr to Height, width
	leax	4,x		; X = pixel data
	;; outter loop: iterate over pixel rows
a@	lda	3,y		; count = width
	pshs	u		; save screen ptr
	;; inner loop: iterate over columns
	;; modify mod+1 and mod+3 to switch directions
b@	ldb	,x+		; get a byte from src
	stb	,u+		; save byte to dest
	deca			; bump counter
	bne	b@		; loop
	;; increment outer loop
	puls	u		; restore original screen ptr
	leau	32,u		; add byte span of screen (goto next line)
	dec	1,y		; bump row counter
	bne	a@		; loop
	lda	#KBANKV
	sta	$FFA0		; remap kernel
	puls	cc,u,pc	; restore regs, return

;
;	Find the address we need on a pixel row basis
;
vidptr:
	ldu	#VIDEO_BASE
	ldd	,x++		; Y into B
	lda	#32
	mul
	leau	d,u
	ldd	,x++		; X
	leau	d,u
	rts

_m6847_video_cmd:
	tfr	d,x
	pshs	u
	jsr	_map_video
	bsr	vidptr		; u now points to the screen
nextline:
	pshs	u		; save it for the next line
nextop:
	ldb	,x+		; op code, 0 = end of line
	beq	endline
oploop:
	lda	,u		; do one screen byte
	anda	,x
	eora	1,x
	sta	,u+
	decb
	bne	oploop		; keep going for run
	leax	2,x
	bra	nextop		; next triplet
endline:
	puls	u		; get position back
	leau	32,u		; down one scan line
	ldb	,x+		; get next op - 0,0 means end and done
	bne	oploop
	jsr	_unmap_video
	puls	u,pc

